//! sieve-bench — reproducible benchmark runner for sieve.
//!
//! Reads one or more corpora (jailbreak + benign), runs the default
//! Scanner over each input, and writes a Markdown REPORT.md with
//! per-corpus detection rate, FPR, and p50 / p99 latency.

use std::env;
use std::fs;
use std::io::Write;
use std::path::PathBuf;
use std::process::ExitCode;
use std::time::Instant;

use sieve_core::{Decision, Scanner};

#[derive(Default)]
struct Args {
    jailbreaks: Vec<PathBuf>,
    benign: Vec<PathBuf>,
    extra: Vec<(String, PathBuf)>,
    output: PathBuf,
}

fn parse_args() -> Result<Args, String> {
    let mut args = Args {
        output: PathBuf::from("benchmarks/REPORT.md"),
        ..Default::default()
    };
    let mut it = env::args().skip(1);
    while let Some(a) = it.next() {
        match a.as_str() {
            "--jailbreaks" => args
                .jailbreaks
                .push(PathBuf::from(it.next().ok_or("missing path")?)),
            "--benign" => args
                .benign
                .push(PathBuf::from(it.next().ok_or("missing path")?)),
            "--jbb" => args.extra.push((
                "JailbreakBench".into(),
                PathBuf::from(it.next().ok_or("missing path")?),
            )),
            "--garak" => args.extra.push((
                "garak".into(),
                PathBuf::from(it.next().ok_or("missing path")?),
            )),
            "--acl" => args.extra.push((
                "ACL'25 bypasses".into(),
                PathBuf::from(it.next().ok_or("missing path")?),
            )),
            "--output" => args.output = PathBuf::from(it.next().ok_or("missing path")?),
            other => return Err(format!("unknown flag: {other}")),
        }
    }
    Ok(args)
}

fn parse_corpus(path: &PathBuf) -> Result<Vec<String>, String> {
    let raw = fs::read_to_string(path).map_err(|e| format!("read {path:?}: {e}"))?;
    Ok(raw
        .lines()
        .map(|l| l.trim().to_string())
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .collect())
}

struct CorpusReport {
    name: String,
    size: usize,
    blocks: usize,
    flags: usize,
    allows: usize,
    p50_us: u64,
    p99_us: u64,
}

fn run_corpus(scanner: &Scanner, name: &str, inputs: &[String]) -> CorpusReport {
    let mut blocks = 0usize;
    let mut flags = 0usize;
    let mut allows = 0usize;
    let mut latencies = Vec::with_capacity(inputs.len());

    for line in inputs {
        let t0 = Instant::now();
        let v = scanner.scan_input("You are a helpful assistant.", line);
        let elapsed = u64::try_from(t0.elapsed().as_micros()).unwrap_or(u64::MAX);
        latencies.push(elapsed);
        match v.decision {
            Decision::Block => blocks += 1,
            Decision::Flag => flags += 1,
            Decision::Allow => allows += 1,
        }
    }
    latencies.sort_unstable();
    let p50 = percentile(&latencies, 50);
    let p99 = percentile(&latencies, 99);
    CorpusReport {
        name: name.to_string(),
        size: inputs.len(),
        blocks,
        flags,
        allows,
        p50_us: p50,
        p99_us: p99,
    }
}

fn percentile(sorted: &[u64], p: usize) -> u64 {
    if sorted.is_empty() {
        return 0;
    }
    let idx = sorted.len().saturating_sub(1) * p / 100;
    sorted.get(idx).copied().unwrap_or(0)
}

fn pct(n: usize, d: usize) -> String {
    if d == 0 {
        return "n/a".into();
    }
    #[allow(clippy::cast_precision_loss)]
    let v = (n as f64) * 100.0 / (d as f64);
    format!("{v:.1}%")
}

fn write_report(out: &PathBuf, reports: &[CorpusReport]) -> Result<(), String> {
    let mut s = String::new();
    s.push_str("# sieve benchmark report\n\n");
    s.push_str("Generated by `benchmarks/run.sh`. See PRD §11.6 and\n");
    s.push_str("`IMPLEMENTATION_PROMPT.md` Phase 15 for methodology.\n\n");
    s.push_str("## Methodology\n\n");
    s.push_str("Each line of each corpus is run through `Scanner::default()` with\n");
    s.push_str("the same system prompt (`\"You are a helpful assistant.\"`). The\n");
    s.push_str("`Decision` returned is bucketed Block / Flag / Allow. Per-call\n");
    s.push_str("latency is measured around `scan_input` only (no I/O).\n\n");
    s.push_str("## Per-corpus results\n\n");
    s.push_str("| Corpus | Size | Block | Flag | Allow | Detection (Block) | p50 latency | p99 latency |\n");
    s.push_str("|---|---:|---:|---:|---:|---:|---:|---:|\n");
    for r in reports {
        s.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} | {}µs | {}µs |\n",
            r.name,
            r.size,
            r.blocks,
            r.flags,
            r.allows,
            pct(r.blocks, r.size),
            r.p50_us,
            r.p99_us,
        ));
    }
    s.push_str("\n## Published competitor numbers (cited)\n\n");
    s.push_str("- Lakera Guard: 74.6% (arXiv 2505.13028, independent eval, 2025).\n");
    s.push_str("- Azure Prompt Shield: 42.98% (same paper).\n");
    s.push_str("- ACL LLMSec 2025 Unicode bypass: 100% evasion against Lakera /\n");
    s.push_str("  Azure / Meta Prompt Guard / ProtectAI v2.\n\n");
    s.push_str("Cross-test comparisons are difficult — different test sets, different\n");
    s.push_str("attacker assumptions, different cost models. We publish our numbers\n");
    s.push_str("with the inputs and the harness so anyone can reproduce them.\n\n");
    s.push_str("## How to extend\n\n");
    s.push_str("- `--jbb path/to/jailbreakbench.json` — JailbreakBench corpus.\n");
    s.push_str("- `--garak path/to/garak-probes.txt` — garak probe dump.\n");
    s.push_str("- `--acl path/to/acl25-bypasses.txt` — ACL'25 cited samples.\n");
    s.push_str("\nEach external corpus is loaded the same way (one input per line,\n");
    s.push_str("blanks + lines starting with `#` ignored) and added as an additional\n");
    s.push_str("row in this table on rerun.\n");

    fs::write(out, s).map_err(|e| format!("write {out:?}: {e}"))?;
    Ok(())
}

fn main() -> ExitCode {
    let args = match parse_args() {
        Ok(a) => a,
        Err(e) => {
            let _ = writeln!(std::io::stderr(), "sieve-bench: {e}");
            return ExitCode::from(2);
        }
    };

    let scanner = Scanner::default();
    let mut reports: Vec<CorpusReport> = Vec::new();

    for p in &args.jailbreaks {
        match parse_corpus(p) {
            Ok(inputs) => reports.push(run_corpus(&scanner, "Jailbreaks (curated)", &inputs)),
            Err(e) => {
                let _ = writeln!(std::io::stderr(), "skip {p:?}: {e}");
            }
        }
    }
    for p in &args.benign {
        match parse_corpus(p) {
            Ok(inputs) => reports.push(run_corpus(&scanner, "Benign (curated)", &inputs)),
            Err(e) => {
                let _ = writeln!(std::io::stderr(), "skip {p:?}: {e}");
            }
        }
    }
    for (name, p) in &args.extra {
        match parse_corpus(p) {
            Ok(inputs) => reports.push(run_corpus(&scanner, name, &inputs)),
            Err(e) => {
                let _ = writeln!(std::io::stderr(), "skip {p:?}: {e}");
            }
        }
    }

    if let Err(e) = write_report(&args.output, &reports) {
        let _ = writeln!(std::io::stderr(), "sieve-bench: {e}");
        return ExitCode::from(1);
    }
    println!("wrote {}", args.output.display());
    ExitCode::SUCCESS
}
